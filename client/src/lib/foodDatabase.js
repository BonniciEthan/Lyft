function parseServings(str, ml) {
  const unit = ml ? 'ml' : 'g';
  const base = [{ label: `100${unit}`, grams: 100 }];
  if (!str) return base;
  const extra = str.split('|').map((part) => {
    const i = part.lastIndexOf('=');
    return { label: part.slice(0, i).trim(), grams: Number(part.slice(i + 1)) };
  });
  return [...base, ...extra.filter((s) => s.label !== base[0].label)];
}

